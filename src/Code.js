/**
 * 計算下一個週一（無條件進位）
 * 如果今天是週一，返回今天
 * 否則返回下一個週一
 */
function getNextMonday(date) {
  const dayOfWeek = date.getDay(); // 0=週日, 1=週一, ..., 6=週六
  
  if (dayOfWeek === 1) {
    // 今天是週一，返回今天
    const monday = new Date(date);
    monday.setHours(0, 0, 0, 0);
    return monday;
  } else {
    // 計算到下一個週一的天數
    const daysUntilMonday = dayOfWeek === 0 ? 1 : (8 - dayOfWeek);
    const monday = new Date(date.getTime() + daysUntilMonday * 24 * 60 * 60 * 1000);
    monday.setHours(0, 0, 0, 0);
    return monday;
  }
}

/**
 * 計算追蹤範圍（過去 N 週）
 */
function getTrackingRange(weeks, fromDate) {
  const startDate = new Date(fromDate.getTime() - weeks * 7 * 24 * 60 * 60 * 1000);
  
  return {
    startDate: startDate,
    endDate: fromDate,
    startTimestamp: Math.floor(startDate.getTime() / 1000),
    endTimestamp: Math.floor(fromDate.getTime() / 1000)
  };
}

/**
 * 從 Facebook API 抓取貼文
 */
function fetchPostsFromFacebook(trackingRange) {
  const url = `https://graph.facebook.com/v21.0/${CONFIG.pageId}/posts`;
  
  const params = {
    access_token: CONFIG.accessToken,
    fields: 'id,message,created_time,likes.summary(true),comments.summary(true),shares,insights.metric(post_impressions_unique)',
    since: trackingRange.startTimestamp,
    until: trackingRange.endTimestamp,
    limit: 100
  };
  
  const queryString = Object.keys(params)
    .map(key => `${key}=${encodeURIComponent(params[key])}`)
    .join('&');
  
  const fullUrl = `${url}?${queryString}`;
  
  try {
    const response = UrlFetchApp.fetch(fullUrl);
    const data = JSON.parse(response.getContentText());
    
    if (!data.data) {
      throw new Error('API 回應格式錯誤');
    }
    
    return data.data.map(post => {
      // 提取觸及人數
      let reach = '';
      if (post.insights && post.insights.data && post.insights.data.length > 0) {
        const impressionsData = post.insights.data.find(item => item.name === 'post_impressions_unique');
        if (impressionsData && impressionsData.values && impressionsData.values.length > 0) {
          reach = impressionsData.values[0].value;
        }
      }
      
      return {
        postId: post.id,
        message: post.message || '(無文字內容)',
        createdTime: new Date(post.created_time),
        likes: post.likes ? post.likes.summary.total_count : 0,
        comments: post.comments ? post.comments.summary.total_count : 0,
        shares: post.shares ? post.shares.count : 0,
        reach: reach  // 觸及人數（自動抓取）
      };
    });
    
  } catch (error) {
    Logger.log(`Facebook API 錯誤：${error.message}`);
    throw new Error(`無法從 Facebook 抓取資料：${error.message}`);
  }
}

/**
 * 按發文月份分組
 */
function groupPostsByMonth(posts) {
  const grouped = {};
  
  posts.forEach(post => {
    const monthKey = formatMonthKey(post.createdTime);
    
    if (!grouped[monthKey]) {
      grouped[monthKey] = [];
    }
    
    grouped[monthKey].push(post);
  });
  
  return grouped;
}

/**
 * 格式化月份鍵值 (YYYY-MM)
 */
function formatMonthKey(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  return `${year}-${month}`;
}

/**
 * 更新指定月份的工作表
 */
function updateMonthSheet(monthKey, posts, statisticsDate) {
  Logger.log(`更新 ${monthKey} 工作表...`);
  
  const spreadsheet = SpreadsheetApp.openById(CONFIG.spreadsheetId);
  let sheet = spreadsheet.getSheetByName(monthKey);
  
  if (!sheet) {
    sheet = createMonthSheet(spreadsheet, monthKey);
  }
  
  // 反轉貼文順序：FB API 回傳是新到舊，我們要舊到新（舊的在上面）
  const reversedPosts = posts.slice().reverse();
  
  // 處理每篇貼文
  reversedPosts.forEach(post => {
    processPost(sheet, post, statisticsDate);
  });
  
  // 自動調整欄寬
  sheet.autoResizeColumns(1, 9);
  
  // 設定「貼文內容」欄位（C 欄，第 3 欄）為文字換行
  const lastRow = sheet.getLastRow();
  if (lastRow > 1) {
    sheet.getRange(2, 3, lastRow - 1, 1).setWrap(true);
  }
}

/**
 * 建立月份工作表
 */
function createMonthSheet(spreadsheet, monthKey) {
  // 插入在索引 0 的位置（最前面）
  // 這樣新月份會在最前面，「設定」工作表在最後面
  const sheet = spreadsheet.insertSheet(monthKey, 0);
  
  const headers = [
    '貼文編號',  // A 欄（會被隱藏）
    '發文時間',  // B 欄
    '貼文文字',  // C 欄
    '追蹤週次',  // D 欄
    '統計日期',  // E 欄
    '按讚數',    // F 欄
    '留言數',    // G 欄
    '分享數',    // H 欄
    '觸及人數'   // I 欄
  ];
  
  sheet.getRange(1, 1, 1, headers.length).setValues([headers]);
  sheet.getRange(1, 1, 1, headers.length)
    .setFontWeight('bold')
    .setBackground('#4285f4')
    .setFontColor('#ffffff');
  
  // 隱藏 A 欄（貼文編號）
  sheet.hideColumns(1);
  
  return sheet;
}

/**
 * 處理單篇貼文
 */
function processPost(sheet, post, statisticsDate) {
  const postId = post.postId;
  
  // 檢查這篇貼文是否已存在
  const existingRows = findPostRows(sheet, postId);
  
  if (existingRows.length === 0) {
    // 新貼文，建立 6 行（從當前統計日期開始）
    createPostRows(sheet, post, statisticsDate);
  }
  
  // 更新對應統計日期的那一列
  updateStatisticsRow(sheet, post, statisticsDate);
}

/**
 * 找到指定貼文 ID 的所有行號
 */
function findPostRows(sheet, postId) {
  const lastRow = sheet.getLastRow();
  if (lastRow < 2) return [];
  
  const idColumn = sheet.getRange(2, 1, lastRow - 1, 1).getValues();
  const rows = [];
  
  idColumn.forEach((row, index) => {
    if (row[0] === postId) {
      rows.push(index + 2);
    }
  });
  
  return rows;
}

/**
 * 為新貼文建立 6 行（從發文日期進位到下一個週一開始）
 */
function createPostRows(sheet, post, statisticsDate) {
  Logger.log(`建立新貼文：${post.postId}`);
  
  const lastRow = sheet.getLastRow();
  const startRow = lastRow + 1;
  
  // 計算第一個統計日期：發文日期進位到下一個週一
  const firstMonday = getNextMondayAfterPost(post.createdTime);
  
  // 從第一個統計日期開始，建立 6 個週一
  const rows = [];
  for (let week = 1; week <= CONFIG.trackingWeeks; week++) {
    const monday = new Date(firstMonday.getTime() + (week - 1) * 7 * 24 * 60 * 60 * 1000);
    
    rows.push([
      post.postId,  // A 欄：貼文 ID（每行都有，不合併，稍後隱藏）
      formatDateTime(post.createdTime),  // B 欄：發文時間
      post.message,  // C 欄：貼文內容
      `第${week}週`,  // D 欄：追蹤週次
      formatDate(monday),  // E 欄：統計日期
      '',  // F 欄：按讚數（待填）
      '',  // G 欄：留言數（待填）
      '',  // H 欄：分享數（待填）
      ''   // I 欄：觸及人數（待填）
    ]);
  }
  
  // 寫入資料
  sheet.getRange(startRow, 1, rows.length, 9).setValues(rows);
  
  // 合併儲存格：發文時間（B 欄，第 2 欄）
  if (CONFIG.trackingWeeks > 1) {
    sheet.getRange(startRow, 2, CONFIG.trackingWeeks, 1).merge();
  }
  
  // 合併儲存格：貼文內容（C 欄，第 3 欄）
  if (CONFIG.trackingWeeks > 1) {
    sheet.getRange(startRow, 3, CONFIG.trackingWeeks, 1).merge();
  }
  
  // 設定垂直對齊方式為靠上
  sheet.getRange(startRow, 2, CONFIG.trackingWeeks, 2).setVerticalAlignment('top');
  
  // 隱藏 A 欄（貼文 ID）- 只需設定一次，不用每次都設
  // 在 createMonthSheet 中處理
}

/**
 * 取得發文日期之後的下一個週一（不包含當天）
 */
function getNextMondayAfterPost(postDate) {
  const dayOfWeek = postDate.getDay();  // 0=週日, 1=週一, ..., 6=週六
  
  // 計算到下一個週一的天數（一定要到「下一個」週一，不是當週）
  const daysUntilMonday = dayOfWeek === 0 ? 1 : (8 - dayOfWeek);
  
  const monday = new Date(postDate.getTime() + daysUntilMonday * 24 * 60 * 60 * 1000);
  monday.setHours(0, 0, 0, 0);
  return monday;
}

/**
 * 更新指定統計日期的那一列
 */
function updateStatisticsRow(sheet, post, statisticsDate) {
  const postId = post.postId;
  const targetDate = formatDate(statisticsDate);  // 字串格式："2026-01-26"
  
  // 找到「貼文 ID + 統計日期」對應的列
  const lastRow = sheet.getLastRow();
  if (lastRow < 2) return;
  
  // 讀取 A 欄（貼文 ID）和 E 欄（統計日期）
  const data = sheet.getRange(2, 1, lastRow - 1, 5).getValues();
  
  for (let i = 0; i < data.length; i++) {
    const rowPostId = data[i][0];  // A 欄（索引 0）
    const rowStatDate = data[i][4];  // E 欄（索引 4）
    
    // 統一轉換成字串格式比較
    const rowStatDateStr = typeof rowStatDate === 'string' 
      ? rowStatDate 
      : (rowStatDate instanceof Date ? formatDate(rowStatDate) : String(rowStatDate));
    
    if (rowPostId === postId && rowStatDateStr === targetDate) {
      const rowNumber = i + 2;
      
      // 更新按讚、留言、分享數、觸及人數（F、G、H、I 欄，第 6、7、8、9 欄）
      sheet.getRange(rowNumber, 6).setValue(post.likes);
      sheet.getRange(rowNumber, 7).setValue(post.comments);
      sheet.getRange(rowNumber, 8).setValue(post.shares);
      
      // 更新觸及人數（如果 API 有回傳）
      if (post.reach !== '') {
        sheet.getRange(rowNumber, 9).setValue(post.reach);
      }
      
      Logger.log(`更新貼文 ${postId} 在 ${targetDate} 的數據：按讚 ${post.likes}、留言 ${post.comments}、分享 ${post.shares}、觸及 ${post.reach || '(無)'}`);
      return;
    }
  }
  
  Logger.log(`找不到貼文 ${postId} 在 ${targetDate} 的列（可能統計日期不在追蹤範圍內）`);
}

/**
 * 更新最後執行時間
 */
function updateLastRunTime(executeDate, statisticsDate) {
  const spreadsheet = SpreadsheetApp.openById(CONFIG.spreadsheetId);
  const settingsSheet = spreadsheet.getSheetByName('設定');
  
  if (!settingsSheet) return;
  
  const data = settingsSheet.getRange('A2:A10').getValues();
  for (let i = 0; i < data.length; i++) {
    if (data[i][0] === '最後執行時間') {
      const message = `${formatDateTime(executeDate)} (統計日期: ${formatDate(statisticsDate)})`;
      settingsSheet.getRange(i + 2, 2).setValue(message);
      break;
    }
  }
}

